def test_get_pikapika():
    # apunta a la api
    url = "https://pokeapi.co/api/v2/pokemon/pikachu"

    respuesta = requests.get(url)
    # Afirmar que el status code es 200 / Clase 19 
    assert respuesta.status_code == 200, f"Status esperado 200, pero fue {respuesta.status_code}"
    print("Caso 2: Verificación de status exitosa: Status code = 200")
    print("PIKA PIKA!")
    # asignación de la respuesta de la url a una variable
    

    # pasaje de la respuesta del GET a la API a json para manipularlo y obtener datos
    respuesta_json = respuesta.json()

    # TODO: puede hacerse sin asignarse a una variable? por qué en este caso un get y en los otros no, sólo
    # para la asignación de variable?

    # verificaciones tomadas de clase 19 - Existencia de la clave, si es numérica y si tiene información o está vacía
    assert "base_experience" in respuesta_json, "No existe la clave 'base_experience'"
    # assert isinstance(respuesta["base_experience"], int), "El campo 'base_experience' no es numerico"
    # assert respuesta["base_experience"].strip() != "", "El campo 'base_experience' está vacío"

    experiencia_base = respuesta_json.get("base_experience")
    assert 10 < experiencia_base < 1000, f"El valor de la clave 'base_experience' es menor a 10 o mayor a 1000"
    print("Verificación de clave-valor 'base_experience' exitosa: es mayor a 10 y menor a 1000.")
    
    assert respuesta_json["types"][0]["type"]["name"] == "electric", "La clave 'type' tiene un valor distinto al esperado (Electric)"
    
    print("Verificación de clave-valor 'type' exitosa: Pikachu es electric")

    print("Verificación de Caso 3 terminada. No se encontraron errores")


